create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'MovieTogether user',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  host_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  room_code text not null unique check (room_code ~ '^[A-Z0-9]{6}$'),
  password_hash text,
  status text not null default 'active' check (status in ('active', 'ended')),
  created_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.room_members (
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('host', 'member')),
  status text not null default 'approved' check (status in ('pending', 'approved', 'rejected', 'removed')),
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.playback_state (
  room_id uuid primary key references public.rooms(id) on delete cascade,
  source_type text not null check (source_type in ('youtube', 'official_link', 'local_file', 'authorized_upload')),
  source_id text not null,
  is_playing boolean not null default false,
  position_seconds numeric(12, 3) not null default 0 check (position_seconds >= 0),
  updated_by uuid not null references public.profiles(id),
  version bigint not null default 0,
  updated_at timestamptz not null default now()
);

create index if not exists room_members_user_idx on public.room_members(user_id);
create index if not exists chat_messages_room_created_idx on public.chat_messages(room_id, created_at);

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.room_members enable row level security;
alter table public.chat_messages enable row level security;
alter table public.playback_state enable row level security;

create or replace function private.is_room_host(target_room_id uuid, target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.rooms
    where id = target_room_id and host_id = target_user_id
  );
$$;

create or replace function private.is_approved_room_member(target_room_id uuid, target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.room_members
    where room_id = target_room_id
      and user_id = target_user_id
      and status = 'approved'
  );
$$;

create or replace function private.is_room_member(target_room_id uuid, target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.room_members
    where room_id = target_room_id
      and user_id = target_user_id
      and status in ('pending', 'approved')
  );
$$;

create or replace function private.lookup_active_room_by_code(target_room_code text)
returns table(id uuid)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select rooms.id
  from public.rooms
  where rooms.room_code = upper(trim(target_room_code))
    and rooms.status = 'active'
  limit 1;
$$;

create or replace function public.lookup_active_room_by_code(target_room_code text)
returns table(id uuid)
language sql
stable
security invoker
set search_path = public, private
as $$
  select * from private.lookup_active_room_by_code(target_room_code);
$$;

grant usage on schema private to authenticated;
revoke all on function private.is_room_host(uuid, uuid) from public;
revoke all on function private.is_approved_room_member(uuid, uuid) from public;
revoke all on function private.is_room_member(uuid, uuid) from public;
revoke all on function private.lookup_active_room_by_code(text) from public;
grant execute on function private.is_room_host(uuid, uuid) to authenticated;
grant execute on function private.is_approved_room_member(uuid, uuid) to authenticated;
grant execute on function private.is_room_member(uuid, uuid) to authenticated;
revoke all on function public.lookup_active_room_by_code(text) from public;
grant execute on function public.lookup_active_room_by_code(text) to authenticated;

create policy "profiles are visible to authenticated users"
  on public.profiles for select to authenticated using (true);
create policy "users update their own profile"
  on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "members can view their rooms"
  on public.rooms for select to authenticated
  using (
    host_id = (select auth.uid())
    or private.is_room_member(id, (select auth.uid()))
  );
create policy "users create their own rooms"
  on public.rooms for insert to authenticated with check (host_id = (select auth.uid()));
create policy "hosts update their rooms"
  on public.rooms for update to authenticated using (host_id = (select auth.uid())) with check (host_id = (select auth.uid()));
create policy "hosts delete their rooms"
  on public.rooms for delete to authenticated using (host_id = (select auth.uid()));

create policy "members can view room membership"
  on public.room_members for select to authenticated
  using (user_id = (select auth.uid()) or private.is_room_host(room_id, (select auth.uid())));
create policy "users request membership"
  on public.room_members for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and role = 'member'
    and status = 'pending'
  );
create policy "hosts manage membership"
  on public.room_members for update to authenticated
  using (private.is_room_host(room_id, (select auth.uid())))
  with check (private.is_room_host(room_id, (select auth.uid())));

create policy "members can read room chat"
  on public.chat_messages for select to authenticated
  using (private.is_approved_room_member(room_id, (select auth.uid())));
create policy "members can send room chat"
  on public.chat_messages for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and private.is_approved_room_member(room_id, (select auth.uid()))
  );

create policy "members can read playback"
  on public.playback_state for select to authenticated
  using (private.is_approved_room_member(room_id, (select auth.uid())));
create policy "hosts control playback"
  on public.playback_state for all to authenticated
  using (private.is_room_host(room_id, (select auth.uid())))
  with check (private.is_room_host(room_id, (select auth.uid())));

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'MovieTogether user'));
  return new;
end;
$$;

create or replace function private.add_room_host()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.room_members (room_id, user_id, role, status)
  values (new.id, new.host_id, 'host', 'approved');
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure private.handle_new_user();

drop trigger if exists on_room_created on public.rooms;
create trigger on_room_created
  after insert on public.rooms
  for each row execute procedure private.add_room_host();
